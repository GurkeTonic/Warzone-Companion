/* Application bootstrap. Loaded before router.js, after every view script.
   Each page (/, /warzones/, /map/, ...) is a real subpage shipping this same
   shell with every panel already in the DOM (see index.html) — only one is
   shown at a time. <body data-tab="..."> names the view the page shows on
   first load. router.js intercepts nav clicks after that and calls runTab()
   directly instead of letting the browser navigate, so tab switches never
   reload the page; a real navigation (JS disabled, crawler, direct link)
   still lands on the matching static subpage generated by
   tools/build_pages.py. */
"use strict";

const App = (() => {
  /* Order defines the rail and the bottom nav. `path` is the English path;
     localPath() turns it into the page's own language, and the result must
     be a key in ROUTES so soft navigation and the static pages agree. */
  const TABS = {
    overview:  { view: OverviewView,  panel: "panel-overview",  path: "/" },
    warzones:  { view: WarzonesView,  panel: "panel-warzones",  path: "/warzones/" },
    map:       { view: MapView,       panel: "panel-map",       path: "/map/" },
    history:   { view: HistoryView,   panel: "panel-history",   path: "/history/" },
    lp:        { view: LpStoreView,   panel: "panel-lp",        path: "/lp/" },
    boards:    { view: BoardsView,    panel: "panel-boards",    path: "/leaderboards/" },
    campaigns: { view: CampaignsView, panel: "panel-campaigns", path: "/campaigns/" },
    faq:       { view: FaqView,       panel: "panel-faq",       path: "/faq/" }
  };

  /* Matches the --tbl/--card swap in css/app.css. Views ask this instead of
     rendering both a table and a card list into the DOM and hiding one. */
  const NARROW = window.matchMedia("(max-width: 900px)");

  let activeTab = "overview";
  const loaded = new Set();
  /* Separate from `loaded`, which the refresh button deliberately deletes
     from to force a reload — everLoaded never shrinks, so a force refresh
     never re-triggers the skeleton over an already-visible table. */
  const everLoaded = new Set();
  let autoTimer = null;
  let updatedText = "";
  const BOTTOM_N = 4;

  const $ = (id) => document.getElementById(id);
  const isNarrow = () => NARROW.matches;

  function updateLiveChip(on) {
    $("auto-refresh").setAttribute("aria-pressed", String(on));
  }

  /* Header nav and bottom nav render from the same TABS order; real <a href>
     so middle-click, "open in new tab" and crawlers all still work. The
     header nav replaced the left rail on 9.10.2026: the overview's two maps
     need the width, and eight words fit in one line from 1100px. */
  function renderNav() {
    $("rail").setAttribute("aria-label", t("nav_label"));
    $("bottom-nav").setAttribute("aria-label", t("nav_label"));
    $("rail").innerHTML = Object.entries(TABS).map(([id, tab]) => `
      <a href="${localPath(tab.path)}" id="rail-tab-${id}" class="${id === activeTab ? "active" : ""}"${id === activeTab ? ' aria-current="page"' : ""}>${esc(t("tab_" + id))}</a>`).join("");

    /* Phone: the first four in the bar, the rest behind "More" — eight
       labels do not fit 390px (before 5.10.2026 two of them ran off the
       edge). "More" carries the active marker when one of its tabs is open. */
    const ids = Object.keys(TABS);
    const main = ids.slice(0, BOTTOM_N), rest = ids.slice(BOTTOM_N);
    const link = (id, prefix) => `
      <a href="${localPath(TABS[id].path)}" id="${prefix}-tab-${id}" class="${id === activeTab ? "active" : ""}">${esc(t("tab_" + id))}</a>`;
    $("bottom-nav").innerHTML = main.map(id => link(id, "bot")).join("") + `
      <button type="button" id="bot-more" class="${rest.includes(activeTab) ? "active" : ""}" aria-expanded="false" aria-controls="more-sheet">${esc(t("tab_more"))}</button>`;
    $("more-sheet").innerHTML = rest.map(id => link(id, "more")).join("");
  }

  function toggleMore(open) {
    const btn = $("bot-more");
    const show = open ?? $("more-sheet").classList.contains("hidden");
    $("more-sheet").classList.toggle("hidden", !show);
    btn?.setAttribute("aria-expanded", String(show));
  }

  function setUpdated(text) {
    updatedText = text;
    const el = $("rail-updated");
    if (el) el.textContent = text;
  }

  function showPanel(tabId) {
    for (const [id, tab] of Object.entries(TABS)) {
      $(tab.panel).classList.toggle("hidden", id !== tabId);
      $("rail-tab-" + id)?.classList.toggle("active", id === tabId);
      if (id === tabId) $("rail-tab-" + id)?.setAttribute("aria-current", "page");
      else $("rail-tab-" + id)?.removeAttribute("aria-current");
      $("bot-tab-" + id)?.classList.toggle("active", id === tabId);
      $("more-tab-" + id)?.classList.toggle("active", id === tabId);
    }
    $("bot-more")?.classList.toggle("active", Object.keys(TABS).indexOf(tabId) >= BOTTOM_N);
    toggleMore(false);
    $("page-title").textContent = t("pt_" + tabId);
    $("page-sub").textContent = t("ps_" + tabId);
    /* Each view owns the chip row; anything left from the previous tab goes. */
    $("page-chips").innerHTML = "";
  }

  function setStatus(state, message = "") {
    $("error").classList.toggle("hidden", state !== "error");
    if (state === "error") $("error").textContent = message;
  }

  /* Central error sink so async view actions never die silently in the console. */
  function reportError(err) {
    const hint = err && err.rateLimited ? t("err_rate_limit") : t("err_hint");
    setStatus("error", t("err_prefix") + (err?.message ?? err) + " — " + hint);
  }

  async function runTab(tabId, force = false) {
    activeTab = tabId;
    showPanel(tabId);
    setStatus("idle"); // clear any error left over from a previous tab
    const tab = TABS[tabId];

    if (loaded.has(tabId) && !force) {
      tab.view.render();
      return;
    }

    if (!everLoaded.has(tabId)) tab.view.skeleton?.();
    setStatus("loading");
    try {
      await tab.view.load();
      loaded.add(tabId);
      everLoaded.add(tabId);
      /* The data comes from the build's ESI snapshot, so show when that was
         fetched, not when the browser loaded it. Set before render() so a
         view with a better answer (the campaigns mirror) can overwrite it. */
      const stamp = await ESI.fetched("fw");
      setUpdated((stamp || new Date().toISOString()).slice(0, 16).replace("T", " ") + " UTC");
      tab.view.render();
      setStatus("idle");
    } catch (err) {
      reportError(err);
    }
    /* The footer waits for the first render (css/app.css): shown at once it
       sat under an empty panel and jumped away, a layout shift. */
    document.body.classList.add("ready");
  }

  /* The header strip summarises both warzones on every tab, so it is fed by
     whichever view last loaded occupancy rather than by the overview alone. */
  function renderFrontStrip(rows) {
    if (!$("front-strip")) return;   // the strip left the header on 9.10.2026
    if (!rows || !rows.length) { $("front-strip").innerHTML = ""; return; }
    $("front-strip").innerHTML = rows.map(r => `
      <div class="strip-cell">
        <span class="strip-tag">${esc(r.tag)}</span>
        <span class="strip-val" style="color:${r.aColor}">${r.a}</span>
        <span class="strip-bar"><span style="width:${r.pct};background:${r.aColor}"></span></span>
        <span class="strip-val" style="color:${r.bColor}">${r.b}</span>
      </div>`).join("");
  }

  /* No stored choice follows the system, like the Almanach. The button
     names what clicking switches *to*, not the current state. */
  function currentTheme() {
    return document.documentElement.dataset.theme
      || (window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark");
  }
  function setTheme(theme) {
    if (theme) {
      document.documentElement.dataset.theme = theme;
      try { localStorage.setItem("tow_theme", theme); } catch { /* private mode */ }
    }
    $("theme-toggle").textContent = currentTheme() === "dark" ? t("theme_to_light") : t("theme_to_dark");
  }

  function setAutoRefresh(on) {
    localStorage.setItem("tow_auto_refresh", on ? "1" : "0");
    updateLiveChip(on);
    if (autoTimer) clearInterval(autoTimer);
    autoTimer = on
      ? setInterval(() => {
          loaded.delete(activeTab);
          runTab(activeTab, true);
        }, CONFIG.AUTO_REFRESH_MS)
      : null;
  }

  function init() {
    /* Turning auto-refresh on also refetches straight away — the header has
       no separate manual refresh in this layout, so this is the way to force
       fresh data on demand. */
    $("auto-refresh").addEventListener("click", () => {
      const on = !autoTimer;
      setAutoRefresh(on);
      if (on) { loaded.delete(activeTab); runTab(activeTab, true); }
    });
    setAutoRefresh(localStorage.getItem("tow_auto_refresh") === "1");

    $("theme-toggle").addEventListener("click", () => {
      setTheme(currentTheme() === "light" ? "dark" : "light");
    });
    setTheme(null);

    document.addEventListener("click", (e) => {
      if (e.target.closest("#bot-more")) { toggleMore(); return; }
      if (!e.target.closest("#more-sheet")) toggleMore(false);
    });

    /* Crossing the table/card breakpoint changes what the views emit, so the
       loaded ones have to be asked for their other layout. */
    NARROW.addEventListener("change", () => {
      for (const tabId of loaded) TABS[tabId].view.render();
    });

    const pageTab = document.body.dataset.tab;
    activeTab = TABS[pageTab] ? pageTab : "overview";
    applyI18n();
    renderNav();
    runTab(activeTab);
  }

  return { init, runTab, reportError, isNarrow, renderFrontStrip, setUpdated, TABS };
})();

document.addEventListener("DOMContentLoaded", App.init);
